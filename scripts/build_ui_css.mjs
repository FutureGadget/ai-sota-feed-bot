#!/usr/bin/env node
// Build web/ui.css: Tailwind CSS v4 + the Basecoat components this site uses.
//
// Basecoat ships every component in one style-pack file (~1.4k lines for Lyra),
// and Tailwind emits @layer components verbatim, so importing the whole pack
// costs ~225 KB of CSS no page reads. This script copies only the components
// listed in ui/basecoat-components.json (structural rules from
// dist/components/<name>.css plus that component's section of the Lyra pack)
// into ui/generated/basecoat.css, then runs the Tailwind CLI on ui/site.css.
//
// Usage:
//   node scripts/build_ui_css.mjs            # one build (minified)
//   node scripts/build_ui_css.mjs --watch    # rebuild on change
//   node scripts/build_ui_css.mjs --check    # CI: fail if web/ui.css is stale

import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const BASECOAT = path.join(ROOT, 'node_modules', 'basecoat-css', 'dist');
const STYLE_PACK = 'lyra';
const LIST = path.join(ROOT, 'ui', 'basecoat-components.json');
const GENERATED = path.join(ROOT, 'ui', 'generated', 'basecoat.css');
const OUTPUT = path.join(ROOT, 'web', 'ui.css');

// Style-pack section titles ("/* Native Select */") -> component file names.
const slug = (title) => title.trim().toLowerCase().replace(/\s+/g, '-');

function packSections(css) {
  // The pack is one `@layer components { ... }` per section, each introduced by
  // a `/* Title */` comment at column 0 or 2.
  const sections = new Map();
  const re = /^ {0,2}\/\* ([A-Z][A-Za-z ]+) \*\/$/gm;
  const marks = [...css.matchAll(re)];
  marks.forEach((m, i) => {
    const end = i + 1 < marks.length ? marks[i + 1].index : css.length;
    sections.set(slug(m[1]), css.slice(m.index, end));
  });
  return sections;
}

function balancedLayer(body) {
  // Sections share one @layer block in the pack, so a slice may open or close
  // it. Strip any @layer wrapper and re-wrap each section on its own.
  const inner = body
    .replace(/@layer components\s*\{/g, '')
    .split('\n');
  let depth = 0;
  const kept = [];
  for (const line of inner) {
    const opens = (line.match(/\{/g) || []).length;
    const closes = (line.match(/\}/g) || []).length;
    if (depth + opens - closes < 0) continue; // the layer's own closing brace
    depth += opens - closes;
    kept.push(line);
  }
  return `@layer components {\n${kept.join('\n').trim()}\n}\n`;
}

// Tailwind's preflight hides [hidden] with !important. Important layered
// declarations beat every normal rule, and site-chrome.css deliberately keeps
// some hidden controls visible (the empty "next day" slot), as it did under
// Oat. Copy preflight with that one declaration made normal.
export function buildPreflight() {
  const src = fs.readFileSync(path.join(ROOT, 'node_modules', 'tailwindcss', 'preflight.css'), 'utf8');
  const rule = /(\[hidden\]:where\(:not\(\[hidden='until-found'\]\)\)\s*\{\s*display:\s*none)\s*!important;/;
  if (!rule.test(src)) throw new Error('preflight.css changed: [hidden] rule not found');
  fs.mkdirSync(path.dirname(GENERATED), { recursive: true });
  fs.writeFileSync(path.join(path.dirname(GENERATED), 'preflight.css'),
    '/* Generated by scripts/build_ui_css.mjs from tailwindcss/preflight.css. Do not edit. */\n' + src.replace(rule, '$1;'));
}

export function buildBasecoatSubset() {
  const wanted = JSON.parse(fs.readFileSync(LIST, 'utf8')).components;
  const pack = packSections(fs.readFileSync(path.join(BASECOAT, 'styles', `${STYLE_PACK}.css`), 'utf8'));
  const version = JSON.parse(fs.readFileSync(path.join(BASECOAT, '..', 'package.json'), 'utf8')).version;
  const parts = [`/* Generated by scripts/build_ui_css.mjs from basecoat-css@${version} (${STYLE_PACK}). Do not edit. */\n`];
  for (const name of wanted) {
    const structural = path.join(BASECOAT, 'components', `${name}.css`);
    if (!fs.existsSync(structural)) throw new Error(`unknown Basecoat component: ${name}`);
    if (!pack.has(name)) throw new Error(`${STYLE_PACK} has no section for: ${name}`);
    parts.push(fs.readFileSync(structural, 'utf8').trim() + '\n');
    parts.push(balancedLayer(pack.get(name)));
  }
  fs.mkdirSync(path.dirname(GENERATED), { recursive: true });
  fs.writeFileSync(GENERATED, parts.join('\n'));
}

// The minifier drops /*! notices from imported files, so the Basecoat MIT
// notice is stamped onto the output after Tailwind's own banner.
function stampLicense(file) {
  const version = JSON.parse(fs.readFileSync(path.join(BASECOAT, '..', 'package.json'), 'utf8')).version;
  const notice = `/*! basecoat-css v${version} (${STYLE_PACK} subset) | MIT License | https://basecoatui.com */\n`;
  const css = fs.readFileSync(file, 'utf8');
  if (!css.includes(notice)) fs.writeFileSync(file, notice + css);
}

function tailwind(args) {
  const bin = path.join(ROOT, 'node_modules', '.bin', 'tailwindcss');
  const res = spawnSync(bin, ['-i', path.join(ROOT, 'ui', 'site.css'), ...args], { cwd: ROOT, stdio: 'inherit' });
  if (res.status !== 0) process.exit(res.status ?? 1);
}

const mode = process.argv[2];
buildPreflight();
buildBasecoatSubset();
if (mode === '--watch') {
  tailwind(['-o', OUTPUT, '--watch']);
} else if (mode === '--check') {
  const tmp = path.join(ROOT, 'ui', 'generated', 'ui.check.css');
  tailwind(['-o', tmp, '--minify']);
  stampLicense(tmp);
  const fresh = fs.readFileSync(tmp, 'utf8');
  const committed = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
  fs.rmSync(tmp);
  if (fresh !== committed) {
    console.error('UI_CSS_STALE: web/ui.css does not match ui/site.css. Run `npm run build:css` and commit web/ui.css.');
    process.exit(1);
  }
  console.log('UI_CSS_FRESH');
} else {
  tailwind(['-o', OUTPUT, '--minify']);
  stampLicense(OUTPUT);
}
