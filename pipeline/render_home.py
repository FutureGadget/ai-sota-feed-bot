#!/usr/bin/env python3
"""Build the home page for every reader language from one template.

``ui/templates/index.html`` is the only hand-edited source of the home page.
This writes ``web/index.html`` and, for every other language in
``config/locales.json``, ``web/<path_prefix>/index.html``. All of them are
committed (``web/`` is served as static files), so a template edit is only done
when the regenerated pages are committed with it; ``tests/test_home_template.py``
fails otherwise.

Text comes from ``config/ui/<code>.json`` (see ``docs/how-to/add-ui-text.md``).
The template marks it with tokens that this module substitutes:

``{{t:key}}``      the dictionary text, HTML-escaped
``{{json:key}}``   the dictionary text for use inside a JSON string
``{{href:/path}}`` the path in this language, where that page exists
``{{var:name}}``   a per-language value (``lang``, ``canonical``,
                   ``alternate_links``, ``language_switch``, ``ui_data``,
                   ``locale_query``)

Scripts read their text through ``t(key, vars)`` over ``window.UI.strings``;
only the keys a page's scripts name are embedded.

``render_static_pages.py`` calls :func:`write_pages` on every run, which is what
keeps the pages fresh in ``run_full.sh`` and ``scripts/build_site.py``. It can
also run alone after a template or dictionary edit::

    python3 pipeline/render_home.py            # rewrite the generated pages
    python3 pipeline/render_home.py --check    # exit 1 if any page is stale
"""

from __future__ import annotations

import argparse
import html as htmllib
import json
import re
import sys
from collections.abc import Mapping
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import locales  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
TEMPLATE_PATH = ROOT / "ui" / "templates" / "index.html"
WEB_DIR = ROOT / "web"
SITE_URL = "https://www.llm-digest.com"

# The crawler-visible feed snapshot lives between these markers inside
# ``<section id="list">``. ``render_static_pages.py`` owns its content (it
# changes with every feed run); the template only carries the empty region.
FEED_SEED_START = "<!-- feed-seed:start -->"
FEED_SEED_END = "<!-- feed-seed:end -->"

BANNER = (
    "<!-- Generated by pipeline/render_home.py from ui/templates/index.html. "
    "Edit the template, not this file. -->"
)

_TOKEN = re.compile(r"\{\{(t|json|href|var):([^{}]+)\}\}")
_SCRIPT = re.compile(r"<script\b([^>]*)>(.*?)</script>", re.S)
_SCRIPT_SRC = re.compile(r"""\bsrc=["']([^"'?]+)""")
_LITERAL = re.compile(r"""(['"`])([A-Za-z][\w.]*)\1""")
_SLUG = re.compile(r"^[a-z0-9-]+$")

# English path -> file that must exist under the language's directory for the
# localized page to be linked. Every path here has a worker route.
LOCALIZED_PAGES = {
    "/daily": "daily/index.html",
    "/weekly": "weekly/index.html",
    "/community": "community/index.html",
    "/playbook": "playbook.html",
}


def page_url(code: str) -> str:
    """The home page's public URL in a language."""
    return f"{SITE_URL}{locales.get(code).path_prefix}/"


def localized_links(code: str) -> dict[str, str]:
    """English path -> path in ``code`` for every page that exists there.

    A link to a page the worker cannot route is a 404 with no fallback, so
    nothing is mapped on faith. The default language maps nothing.
    """
    if code == locales.DEFAULT:
        return {}
    prefix = locales.get(code).path_prefix
    root = WEB_DIR / prefix.lstrip("/")
    links = {"/": f"{prefix}/", "/subscribe": f"/subscribe?lang={code}"}
    for path, rel in LOCALIZED_PAGES.items():
        if (root / rel).is_file():
            links[path] = f"{prefix}{path}"
    for page in sorted((root / "storyline").glob("*.html")):
        if _SLUG.match(page.stem):
            links[f"/storyline/{page.stem}"] = f"{prefix}/storyline/{page.stem}"
    return links


def localize(code: str, path: str) -> str:
    """``path`` in ``code`` when that page exists there, else the English path.

    Covers the pages in :func:`localized_links` and per-story pages, which are
    too many to list in ``window.UI``.
    """
    if code == locales.DEFAULT:
        return path
    mapped = localized_links(code).get(path)
    if mapped:
        return mapped
    prefix = locales.get(code).path_prefix
    if path.startswith("/story/") and (WEB_DIR / prefix.lstrip("/") / "story" / f"{path[7:]}.html").is_file():
        return f"{prefix}{path}"
    return path


def _alternate_links(code: str) -> str:
    rows = [
        f'  <link rel="alternate" hreflang="{c}" href="{page_url(c)}" />' for c in locales.LOCALES
    ]
    rows.append(f'  <link rel="alternate" hreflang="x-default" href="{page_url(locales.DEFAULT)}" />')
    return "\n".join(rows)


def _language_switch(code: str) -> str:
    """Links to the home page in every other language (shown by site-chrome.js
    only to visitors whose browser prefers that language)."""
    rows = []
    for other in locales.others(code):
        label = htmllib.escape(locales.get(other).label)
        rows.append(
            f'<a class="site-language-action" href="{locales.get(other).path_prefix}/"'
            f' data-language-link data-language-locale="{other}" hidden'
            f' aria-label="Read this page in {label}" title="Read in {label}">'
            f'<span aria-hidden="true">🌐</span><span>{other.upper()}</span></a>'
        )
    return "\n        ".join(rows)


def script_text(html: str) -> str:
    """Every script a page runs: its inline scripts plus the local files it loads."""
    parts = []
    for attrs, body in _SCRIPT.findall(html):
        src = _SCRIPT_SRC.search(attrs)
        if src is None:
            parts.append(body)
        elif src.group(1).startswith("/"):
            file = WEB_DIR / src.group(1).lstrip("/")
            if file.is_file():
                parts.append(file.read_text(encoding="utf-8"))
    return "\n".join(parts)


def _ui_data(code: str, strings: Mapping[str, str], html: str) -> str:
    """``window.UI`` for the page: the strings its scripts name, plus link map."""
    named = {m.group(2) for m in _LITERAL.finditer(script_text(html))}
    data = {
        "locale": code,
        "defaultLocale": locales.DEFAULT,
        "strings": {key: strings[key] for key in sorted(named & strings.keys())},
        "links": localized_links(code),
    }
    text = json.dumps(data, ensure_ascii=False, indent=2).replace("</", "<\\/")
    return text.replace("\n", "\n    ")


def _text(strings: Mapping[str, str], key: str, code: str) -> str:
    try:
        return strings[key]
    except KeyError:
        raise KeyError(f"ui/templates/index.html uses '{key}' but config/ui/{code}.json has no such key") from None


def substitute(template: str, code: str) -> str:
    """Replace every token in ``template`` with its ``code`` value."""
    strings = locales.ui(code)
    links = localized_links(code)
    values = {
        "lang": code,
        "canonical": page_url(code),
        "alternate_links": _alternate_links(code),
        "language_switch": _language_switch(code),
        "locale_query": "" if code == locales.DEFAULT else f"?locale={code}",
    }

    def replace(match: re.Match[str]) -> str:
        kind, name = match.group(1), match.group(2)
        if kind == "t":
            return htmllib.escape(_text(strings, name, code), quote=True)
        if kind == "json":
            return json.dumps(_text(strings, name, code), ensure_ascii=False)[1:-1].replace("</", "<\\/")
        if kind == "href":
            return htmllib.escape(links.get(name, name), quote=True)
        if name == "ui_data":
            return match.group(0)  # needs the finished page, see below
        return values[name]

    html = _TOKEN.sub(replace, template)
    return html.replace("{{var:ui_data}}", _ui_data(code, strings, html))


def output_path(code: str) -> Path:
    """Where a language's generated home page is served from."""
    return WEB_DIR / locales.get(code).path_prefix.lstrip("/") / "index.html"


def seed_region(html: str) -> str | None:
    """The marker-delimited feed snapshot in ``html``, markers included."""
    start = html.find(FEED_SEED_START)
    end = html.find(FEED_SEED_END)
    if start == -1 or end == -1 or end < start:
        return None
    return html[start : end + len(FEED_SEED_END)]


def _with_seed(html: str, seed: str) -> str:
    region = seed_region(html)
    if region is None:
        raise ValueError("home template has no feed-seed markers")
    return html.replace(region, seed, 1)


def render(code: str, template: str, *, seed: str | None = None) -> str:
    """One language's home page.

    ``seed`` is the feed snapshot block (markers included) from
    ``render_static_pages.py``. Without it the page keeps the snapshot already
    in its generated file, so a template-only rebuild never blanks the seed.
    """
    html = substitute(template, code)
    if seed is None:
        path = output_path(code)
        if path.is_file():
            seed = seed_region(path.read_text(encoding="utf-8"))
    if seed is not None:
        html = _with_seed(html, seed)
    head, sep, rest = html.partition("\n")
    return f"{head}\n{BANNER}\n{rest}" if sep else html


def write_pages(seeds: Mapping[str, str] | None = None) -> list[Path]:
    """Write every language's home page; returns the paths that changed."""
    template = TEMPLATE_PATH.read_text(encoding="utf-8")
    changed: list[Path] = []
    for code in locales.LOCALES:
        path = output_path(code)
        html = render(code, template, seed=(seeds or {}).get(code))
        if path.is_file() and path.read_text(encoding="utf-8") == html:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(html, encoding="utf-8")
        changed.append(path)
    return changed


def stale_pages() -> list[Path]:
    """Generated pages that differ from what the template produces now.

    The feed snapshot is data, not template, so it is compared as committed.
    """
    template = TEMPLATE_PATH.read_text(encoding="utf-8")
    stale = []
    for code in locales.LOCALES:
        path = output_path(code)
        if not path.is_file() or path.read_text(encoding="utf-8") != render(code, template):
            stale.append(path)
    return stale


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if a generated page is stale")
    args = ap.parse_args()
    if args.check:
        stale = stale_pages()
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}; run python3 pipeline/render_home.py", file=sys.stderr)
        return 1 if stale else 0
    for path in write_pages():
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
