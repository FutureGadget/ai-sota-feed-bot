FEED_SEED_START = "<!-- feed-seed:start -->"
FEED_SEED_END = "<!-- feed-seed:end -->"
FEED_SEED_MAX_ITEMS = 12


def seed_feed_shell(base_url: str, story_sids: set[str]) -> int:
    """Splice the latest ranked feed items into the / shell as static markup.

    web/index.html is client-rendered, so crawlers, link unfurlers, and no-JS
    readers see an empty shell. This writes the top items from the committed
    feed snapshot (data/processed/latest.json) into the marker region inside
    <section id="list">; the feed JS overwrites the region on boot, so readers
    with JS never diverge from the live feed. Idempotent: only rewrites the
    shell when the seed content actually changed.
    """
    shell = WEB_DIR / "index.html"
    if not shell.exists():
        return 0
    items = load_json(ROOT / "data" / "processed" / "latest.json")
    if not isinstance(items, list):
        return 0

    def score(it: dict) -> float:
        try:
            return float(it.get("final_score") or 0)
        except (TypeError, ValueError):
            return 0.0

    ranked = sorted(
        (i for i in items if isinstance(i, dict) and i.get("title")),
        key=score,
        reverse=True,
    )
    cards = []
    for it in ranked:
        url = safe_http_url(it.get("url"))
        if url == "#":
            continue
        title = squeeze(str(it.get("title")))
        summary = squeeze(str(it.get("summary_1line") or it.get("summary") or ""))
        if summary.lower().rstrip(".") == title.lower().rstrip("."):
            summary = ""  # echoing the headline reads as duplication
        sid = story_sid(url)
        perma = (
            f' <a href="/story/{sid}">Context &amp; related coverage →</a>'
            if sid in story_sids
            else ""
        )
        published = parse_dt(it.get("published"))
        meta = " · ".join(
            x
            for x in (source_domain(url), published.date().isoformat() if published else "")
            if x
        )
        body = f"<p>{escape(clip(summary, 240))}{perma}</p>" if summary or perma else ""
        cards.append(
            '<article class="seed-item">'
            f'<p class="seed-meta">{escape(meta)}</p>'
            f'<h3><a href="{escape(url)}" rel="noopener">{escape(title)}</a></h3>'
            f"{body}</article>"
        )
        if len(cards) == FEED_SEED_MAX_ITEMS:
            break
    if not cards:
        return 0
    block = (
        f"{FEED_SEED_START}\n"
        "      <!-- Generated by pipeline/render_static_pages.py from data/processed/latest.json.\n"
        "           Crawler/no-JS-visible feed snapshot; the feed JS replaces this region on boot.\n"
        "           Do not hand-edit between these markers. -->\n"
        '      <div class="feed-seed">\n'
        "        <h2>Today's top signals</h2>\n        "
        + "\n        ".join(cards)
        + '\n        <p class="seed-more"><a href="/daily">Prefer it summarized? Read the daily recap →</a></p>\n'
        "      </div>\n"
        f"      {FEED_SEED_END}"
    )
    html = shell.read_text(encoding="utf-8")
    start = html.find(FEED_SEED_START)
    end = html.find(FEED_SEED_END)
    if start == -1 or end == -1 or end < start:
        print(
            "warning: feed-seed markers missing in web/index.html; seed skipped",
            file=sys.stderr,
        )
        return 0
    new_html = html[:start] + block + html[end + len(FEED_SEED_END):]
    if new_html != html:
        shell.write_text(new_html, encoding="utf-8")
    return len(cards)


def prune_orphans(out_dir: Path, html_re: re.Pattern, keep: set[str]) -> None:
    if not out_dir.is_dir():
        return
    for path in out_dir.glob("*.html"):
        if html_re.match(path.name) and path.name not in keep:
            path.unlink()
            print(f"pruned stale page: {path.relative_to(ROOT)}")


def week_end_date(week_id: str) -> str | None:
    """End (Sunday) of an ISO week id 'YYYY-Www', for sitemap lastmod."""
    m = re.match(r"^(\d{4})-W(\d{2})$", str(week_id))
    if not m:
        return None
    try:
        return date.fromisocalendar(int(m.group(1)), int(m.group(2)), 7).isoformat()
    except ValueError:
        return None


def write_sitemap(
    base_url: str,
    days: list[str],
    weeks: list[str],
    stories: list[tuple[str, str | None]] | None = None,
    storylines: list[tuple[str, str | None]] | None = None,
    topics: list[tuple[str, str | None]] | None = None,
    foundations: list[tuple[str, str | None]] | None = None,
) -> None:
    today = datetime.now(timezone.utc).date().isoformat()
    entries: list[tuple[str, str | None, str | None]] = [
        (f"{base_url}/", today, "hourly"),
        (f"{base_url}/daily", today, "daily"),
        (f"{base_url}/weekly", today, "weekly"),
        (f"{base_url}/subscribe", today, "monthly"),
        (f"{base_url}/storylines", today, "daily"),
        (f"{base_url}/voices", today, "monthly"),
        (f"{base_url}/playbook", today, "daily"),
    ]
    if topics:
        entries.append((f"{base_url}/map", today, "weekly"))
        entries += [
            (f"{base_url}/topic/{slug}", lastmod, "weekly") for slug, lastmod in topics
        ]
    if foundations:
        entries.append((f"{base_url}/foundations", today, "weekly"))
        entries += [
            (f"{base_url}/foundations/{slug}", lastmod, "monthly")
            for slug, lastmod in foundations
        ]
    entries += [(f"{base_url}/daily/{d}", d, None) for d in days]
    # Weekly recaps: lastmod = the week's end date (Sunday) when derivable.
    for w in weeks:
        entries.append((f"{base_url}/weekly/{w}", week_end_date(w), None))
    entries += [
        (f"{base_url}/storyline/{slug}", lastmod, "daily")
        for slug, lastmod in storylines or []
    ]
    entries += [(f"{base_url}/story/{sid}", lastmod, None) for sid, lastmod in stories or []]

    rows = []
    for loc, lastmod, changefreq in entries:
        parts = [f"<loc>{escape(loc)}</loc>"]
        if lastmod:
            parts.append(f"<lastmod>{escape(lastmod)}</lastmod>")
        if changefreq:
            parts.append(f"<changefreq>{escape(changefreq)}</changefreq>")
        rows.append("  <url>" + "".join(parts) + "</url>")
    xml = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + "\n".join(rows)
        + "\n</urlset>\n"
    )
    (WEB_DIR / "sitemap.xml").write_text(xml, encoding="utf-8")


def write_robots(base_url: str) -> None:
    (WEB_DIR / "robots.txt").write_text(
        f"User-agent: *\nAllow: /\n\nSitemap: {base_url}/sitemap.xml\n", encoding="utf-8"
    )


