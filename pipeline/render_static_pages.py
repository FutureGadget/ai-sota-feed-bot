def prune_orphans(out_dir: Path, html_re: re.Pattern, keep: set[str]) -> None:
    if not out_dir.is_dir():
        return
    for path in out_dir.glob("*.html"):
        if html_re.match(path.name) and path.name not in keep:
            path.unlink()
            print(f"pruned stale page: {path.relative_to(ROOT)}")


def week_end_date(week_id: str) -> str | None:
    """End (Sunday) of an ISO week id 'YYYY-Www', for sitemap lastmod."""
    m = re.match(r"^(\d{4})-W(\d{2})$", str(week_id))
    if not m:
        return None
    try:
        return date.fromisocalendar(int(m.group(1)), int(m.group(2)), 7).isoformat()
    except ValueError:
        return None


def write_sitemap(
    base_url: str,
    days: list[str],
    weeks: list[str],
    stories: list[tuple[str, str | None]] | None = None,
    storylines: list[tuple[str, str | None]] | None = None,
    topics: list[tuple[str, str | None]] | None = None,
) -> None:
    today = datetime.now(timezone.utc).date().isoformat()
    entries: list[tuple[str, str | None, str | None]] = [
        (f"{base_url}/", today, "hourly"),
        (f"{base_url}/daily", today, "daily"),
        (f"{base_url}/weekly", today, "weekly"),
        (f"{base_url}/storylines", today, "daily"),
        (f"{base_url}/voices", today, "monthly"),
    ]
    if topics:
        entries.append((f"{base_url}/map", today, "weekly"))
        entries += [
            (f"{base_url}/topic/{slug}", lastmod, "weekly") for slug, lastmod in topics
        ]
    entries += [(f"{base_url}/daily/{d}", d, None) for d in days]
    # Weekly recaps: lastmod = the week's end date (Sunday) when derivable.
    for w in weeks:
        entries.append((f"{base_url}/weekly/{w}", week_end_date(w), None))
    entries += [
        (f"{base_url}/storyline/{slug}", lastmod, "daily")
        for slug, lastmod in storylines or []
    ]
    entries += [(f"{base_url}/story/{sid}", lastmod, None) for sid, lastmod in stories or []]

    rows = []
    for loc, lastmod, changefreq in entries:
        parts = [f"<loc>{escape(loc)}</loc>"]
        if lastmod:
            parts.append(f"<lastmod>{escape(lastmod)}</lastmod>")
        if changefreq:
            parts.append(f"<changefreq>{escape(changefreq)}</changefreq>")
        rows.append("  <url>" + "".join(parts) + "</url>")
    xml = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + "\n".join(rows)
        + "\n</urlset>\n"
    )
    (WEB_DIR / "sitemap.xml").write_text(xml, encoding="utf-8")


def write_robots(base_url: str) -> None:
    (WEB_DIR / "robots.txt").write_text(
        f"User-agent: *\nAllow: /\n\nSitemap: {base_url}/sitemap.xml\n", encoding="utf-8"
    )


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--base-url", default=DEFAULT_BASE_URL, help="public site origin for canonical/sitemap URLs")
    args = ap.parse_args()
    base_url = args.base_url.rstrip("/")

    stories = load_store()
    story_sids = set(stories)

    storyline_details = load_storyline_details()
    index = load_json(STORYLINES_DIR / "index.json") or {}
    active_slugs = {
        str(s.get("slug"))
        for s in (index.get("storylines") or [])
        if isinstance(s, dict) and s.get("slug")
    }
    storyline_of = storyline_membership(storyline_details)

    days = render_daily_pages(base_url, story_sids)
    weeks = render_weekly_pages(base_url, story_sids)
    story_pages, noindexed = render_story_pages(base_url, stories, storyline_of)
    storyline_pages = render_storyline_pages(
        base_url, storyline_details, active_slugs, story_sids
    )
    wiki = load_wiki()
    topic_pages = render_topic_pages(base_url, wiki)
    has_map = render_map_page(base_url, wiki)
    write_sitemap(base_url, days, weeks, story_pages, storyline_pages, topic_pages)
    write_robots(base_url)
    print(
        f"static pages rendered: {len(days)} daily, {len(weeks)} weekly, "
        f"{len(story_pages) + noindexed} story ({noindexed} noindex), "
        f"{len(storyline_details)} storyline ({len(storyline_pages)} active), "
        f"{len(topic_pages)} topic ({'map' if has_map else 'no map'}) "
        "-> web/daily/, web/weekly/, web/story/, web/storyline/, web/topic/"
    )
    n_urls = 5 + len(days) + len(weeks) + len(story_pages) + len(storyline_pages)
    n_urls += (1 + len(topic_pages)) if topic_pages else 0
    print(f"sitemap: web/sitemap.xml ({n_urls} urls), robots: web/robots.txt")
    if not days and not weeks and not story_pages and not storyline_pages:
        print("warning: no recaps or stories found; nothing rendered", file=sys.stderr)


if __name__ == "__main__":
    main()
