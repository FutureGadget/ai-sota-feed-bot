def load_json(path: Path):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return None


def squeeze(text: str) -> str:
    return " ".join(str(text or "").split())


def clip(text: str, limit: int) -> str:
    text = squeeze(text)
    if len(text) <= limit:
        return text
    cut = text[: limit - 1].rsplit(" ", 1)[0]
    return cut + "…"


def story_why(rec: dict) -> str:
    """Reader-facing rationale only; ranking diagnostics belong in topic chips."""
    why = squeeze(rec.get("why_it_matters"))
    if any(why.startswith(prefix) for prefix in MECHANICAL_WHY_PREFIXES):
        return ""
    return why


def story_brief(rec: dict) -> str:
    """Concise permalink copy, never a flattened full RSS/article body."""
    title_cf = squeeze(rec.get("title")).casefold()
    for candidate in (rec.get("summary_1line"), rec.get("summary")):
        brief = squeeze(candidate)
        if brief and brief.casefold() != title_cf:
            return clip(brief, STORY_BRIEF_MAX_CHARS)
    return ""


def intro_paragraphs(intro) -> list[str]:
    if isinstance(intro, list):
        return [squeeze(p) for p in intro if squeeze(p)]
    return [squeeze(p) for p in re.split(r"\n{2,}", str(intro or "")) if squeeze(p)]


def recap_description(recap: dict) -> str:
    """Meta/OG description: first highlight(s) if present, else the intro."""
    highlights = [squeeze(h) for h in recap.get("highlights") or [] if squeeze(h)]
    if highlights:
        return clip(" ".join(highlights), 250)
    paras = intro_paragraphs(recap.get("intro"))
    return clip(paras[0] if paras else "", 250)


def iso_or_none(value) -> str | None:
    try:
        return datetime.fromisoformat(str(value).replace("Z", "+00:00")).isoformat()
    except Exception:
        return None


def fmt_long_date(day_id: str) -> str:
    """e.g. 'Wednesday, Jun 10, 2026' (matches the dynamic page header)."""
    try:
        d = date.fromisoformat(day_id)
    except Exception:
        return str(day_id)
    return f"{d.strftime('%A')}, {d.strftime('%b')} {d.day}, {d.year}"


def safe_http_url(value) -> str:
    s = str(value or "").strip()
    return s if s.startswith("http://") or s.startswith("https://") else "#"


def render_intro(recap: dict) -> str:
    paras = intro_paragraphs(recap.get("intro"))
    highlights = [squeeze(h) for h in recap.get("highlights") or [] if squeeze(h)]
    if not paras and not highlights:
        return ""
    tldr = ""
    if highlights:
        items = "".join(f"<li>{escape(h)}</li>" for h in highlights)
        tldr = (
            '<div class="tldr"><p class="tldr-label">In 30 seconds</p>'
            f"<ul>{items}</ul></div>"
        )
    body = "".join(f"<p>{escape(p)}</p>" for p in paras)
    return f'<div class="intro">{tldr}{body}</div>'


def render_categories(recap: dict, track: str, story_sids: set[str] | None = None) -> str:
    cats = [c for c in recap.get("categories") or [] if isinstance(c, dict)]
    toc = ""
    if len(cats) > 1:
        links = "".join(
            f'<a href="#{escape(str(c.get("slug") or c.get("name") or ""))}">'
            f'{escape(str(c.get("name") or ""))} ({len(c.get("articles") or [])})</a>'
            for c in cats
        )
        toc = f'<nav class="toc">{links}</nav>'

    sections = []
    for c in cats:
        arts = []
        for a in c.get("articles") or []:
            if not isinstance(a, dict):
                continue
            href = safe_http_url(a.get("url"))
            pub = iso_or_none(a.get("published"))
            pub_badge = ""
            if pub:
                d = datetime.fromisoformat(pub)
                pub_badge = f'<span class="badge">{escape(d.strftime("%b"))} {d.day}</span>'
            src_badge = (
                f'<span class="badge">{escape(str(a.get("source")))}</span>'
                if a.get("source")
                else ""
            )
            # Internal link to the story permalink page (hub -> spoke), kept
            # alongside the external title link so titles still go to sources.
            sid = story_sid(a.get("url")) if href != "#" else ""
            detail_link = (
                f'<a class="badge" href="/story/{sid}" data-track="story-link">Details</a>'
                if story_sids and sid in story_sids
                else ""
            )
            summary = (
                f'<p class="art-summary">{escape(squeeze(a.get("summary")))}</p>'
                if squeeze(a.get("summary"))
                else ""
            )
            arts.append(
                "<article>"
                f'<h3><a href="{escape(href)}" target="_blank" rel="noopener" data-track="{track}">'
                f'{escape(squeeze(a.get("title")) or "Untitled")}</a></h3>'
                f'<div class="art-meta">{src_badge}{pub_badge}{detail_link}</div>'
                f"{summary}</article>"
            )
        n = len(arts)
        cat_summary = (
            f'<p class="cat-summary">{escape(squeeze(c.get("summary")))}</p>'
            if squeeze(c.get("summary"))
            else ""
        )
        sections.append(
            f'<section class="cat" id="{escape(str(c.get("slug") or c.get("name") or ""))}">'
            f'<h2>{escape(str(c.get("name") or ""))} <span class="count">{n} item{"" if n == 1 else "s"}</span></h2>'
            f'{cat_summary}<div class="articles">{"".join(arts)}</div></section>'
        )
    return toc + "".join(sections)


def render_archive_select(options: list[tuple[str, str]], current: str, label: str) -> str:
    """Static archive picker; options are (href, text) pairs, newest first."""
    opts = "".join(
        f'<option value="{escape(href)}"{" selected" if href == current else ""}>{escape(text)}</option>'
        for href, text in options
    )
    return (
        f'<label class="archive muted">{escape(label)} '
        f'<select id="archive" aria-label="Choose {escape(label.lower())}">{opts}</select></label>'
    )


def publisher_node(base_url: str) -> dict:
    """schema.org Organization for the publisher, with a logo (rich-result req)."""
    return {
        "@type": "Organization",
        "name": SITE_NAME,
        "url": base_url + "/",
        "logo": {"@type": "ImageObject", "url": base_url + LOGO_PATH},
    }


def breadcrumb_node(base_url: str, trail: list[tuple[str, str]]) -> dict:
    """BreadcrumbList from (name, path) pairs, e.g. [('Home','/'),('Daily','/daily')]."""
    return {
        "@type": "BreadcrumbList",
        "itemListElement": [
            {
                "@type": "ListItem",
                "position": i + 1,
                "name": name,
                "item": base_url + path,
            }
            for i, (name, path) in enumerate(trail)
        ],
    }


def article_node(
    *,
    type_: str,
    title: str,
    description: str,
    canonical: str,
    published: str | None,
    base_url: str,
    image: str = "",
    source_url: str = "",
) -> dict:
    """schema.org Article/NewsArticle node for a recap, story, or storyline."""
    node: dict = {
        "@type": type_,
        "headline": title,
        "description": description,
        "datePublished": published,
        "mainEntityOfPage": canonical,
        "publisher": publisher_node(base_url),
    }
    if image.startswith(("http://", "https://")):
        node["image"] = image
    if source_url.startswith(("http://", "https://")):
        node["isBasedOn"] = source_url  # the original we summarize/link to
    return node


def json_ld_script(nodes: list[dict]) -> str:
    """One <script> carrying a @graph of schema.org nodes (or a single node)."""
    nodes = [n for n in nodes if n]
    if not nodes:
        return ""
    if len(nodes) == 1:
        payload = {"@context": "https://schema.org", **nodes[0]}
    else:
        payload = {"@context": "https://schema.org", "@graph": nodes}
    # Page text must never be able to close the surrounding </script>.
    encoded = json.dumps(payload, ensure_ascii=False).replace("</", "<\\/")
    return f'\n  <script type="application/ld+json">{encoded}</script>'


