def site_section_for_url(url: str) -> str:
    """Map a canonical/detail URL to its parent site destination."""
    path = urlsplit(url).path.rstrip("/") or "/"
    if path == "/" or path.startswith("/story/"):
        return "/"
    if path == "/daily" or path.startswith("/daily/"):
        return "/daily"
    if path == "/weekly" or path.startswith("/weekly/"):
        return "/weekly"
    if path == "/storylines" or path.startswith("/storyline/"):
        return "/storylines"
    if path == "/playbook" or path.startswith("/playbook/"):
        return "/playbook"
    if path == "/map" or path.startswith("/topic/"):
        return "/map"
    if path == "/foundations" or path.startswith("/foundations/"):
        return "/foundations"
    if path == "/voices":
        return "/voices"
    if path == "/subscribe":
        return "/subscribe"
    return ""


def render_site_nav(current: str) -> str:
    """Semantic no-JS navigation; shared JS moves it into Editor's Desk."""
    links = ""
    for href, label in SITE_DESTINATIONS:
        current_attr = ' aria-current="page"' if href == current else ""
        links += (
            f'\n        <a href="{href}" data-site-destination="{href}"'
            f'{current_attr}>{label}</a>'
        )
    return f'<nav class="site-nav-fallback" aria-label="LLM Digest">{links}\n      </nav>'


def load_recaps(directory: Path, file_re: re.Pattern, id_field: str) -> list[dict]:
    recaps = []
    if not directory.is_dir():
        return recaps
    for path in sorted(directory.glob("*.json")):
        if not file_re.match(path.name):
            continue
        data = load_json(path)
        if isinstance(data, dict) and data.get(id_field) and data.get("categories"):
            recaps.append(data)
    recaps.sort(key=lambda r: str(r.get(id_field)), reverse=True)
    return recaps


def meta_line_for(recap: dict) -> str:
    cats = recap.get("categories") or []
    total = recap.get("article_count") or sum(len(c.get("articles") or []) for c in cats)
    return f"{total} articles · {len(cats)} categories"


