            node = nodes.get(slug)
            if not node:
                continue
            sols = "".join(
                f'<a href="/topic/{escape(s["slug"])}">{escape(squeeze(s["title"]))}</a>'
                for s in node.get("solutions") or []
            )
            sol_html = f'<div class="toc">{sols}</div>' if sols else ""
