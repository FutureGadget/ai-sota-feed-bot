# Follow button for static storyline pages. Mirrors the localStorage contract
# in web/storyline.html (FOLLOWS_KEY ai_feed_storyline_follows_v1) so a follow
# made on a static page is recognized by the dynamic /storylines list and vice
# versa.
STORYLINE_FOLLOW_JS = """\
    (function () {
      var KEY = 'ai_feed_storyline_follows_v1';
      var btn = document.getElementById('followBtn');
      if (!btn) return;
      function load() { try { return JSON.parse(localStorage.getItem(KEY) || '{}'); } catch (e) { return {}; } }
      function save(f) { try { localStorage.setItem(KEY, JSON.stringify(f)); } catch (e) {} }
      var slug = btn.dataset.slug, lu = btn.dataset.lastUpdated || '';
      function paint() {
        var on = !!load()[slug];
        btn.setAttribute('aria-pressed', on ? 'true' : 'false');
        btn.textContent = on ? '\\u2713 Following' : '+ Follow this story';
        var hint = document.getElementById('followHint');
        if (hint) hint.textContent = on
          ? 'Following in this browser. New updates will appear on your Live feed.'
          : 'Follow in this browser to see new updates on your Live feed.';
      }
      paint();
      btn.addEventListener('click', function () {
        var f = load();
        if (f[slug]) { delete f[slug]; }
        else { f[slug] = { followed_at: new Date().toISOString(), seen_updated: lu }; }
        save(f);
        paint();
      });
    })();
"""

